def main():
    lines = [l.strip() for l in CORE.read_text(encoding='utf-8').splitlines() if l.strip()]
    out = [MAP.get(l, l) for l in lines]
    seen = set()
    uniq = []
    for w in out:
        if w in seen:
            continue
        seen.add(w)
        uniq.append(w)
    CORE.write_text('\n'.join(uniq) + '\n', encoding='utf-8')
    print(f'✅ {len(uniq)} 個核心詞')


if __name__ == '__main__':
    main()
