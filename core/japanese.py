def masu_of(plain: str) -> str:
    """字典形 → ます形（買います→買う這類不規則另外處理）。"""
    if plain.endswith('う'):
        return plain[:-1] + 'います'
    if plain.endswith('る'):
        return plain[:-1] + 'ります'
    return plain + 'ます'


# ── 動詞與形容詞的形式 ────────────────────────────────────────────────────────

def verb_forms(masu: str) -> set[str]:
    """「ます形」→ 可以寫出來的形式。

    Mini-Japanese 只用 ます 形，所以：
        たべます／たべました／たべません／たべたい／たべましょう
    """
    out = {masu}
    if masu.endswith('ます'):
        stem = masu[:-2]
        out.add(stem + 'ました')
        out.add(stem + 'ません')
        out.add(stem + 'たい')
        out.add(stem + 'ましょう')
    return out


def verb_extra(masu: str) -> set[str]:
    """原形（描述用：〜をする人）。"""
    plain = plain_of(masu)
    out = {plain} if plain != masu else set()
    if plain == 'なる':
        # 「〜になる」的連體修飾形是「〜な」
        out.add('な')
    return out


def adj_forms(ii: str) -> set[str]:
    """形容詞：-い 形。

        良い／良かった／良く（連用形）／悪くない
    """
    out = {ii}
    if ii.endswith('い') and not ii.endswith('ない'):
        out.add(ii[:-1] + 'くない')
        out.add(ii[:-1] + 'く')
    return out


