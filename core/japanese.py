"""日文的音便：字典形 → 語尾變化。

日文的動詞變化有幾個固定規則：

* う段 → て形／た形：書く→書いて、泳ぐ→泳いで、話す→して
* ぬ・ぶ・む段 → て形／た形：読む→読んで、飛ぶ→飛んで、読む→読んだ
* く段 → いて：聞く→聞いて、働く→働いて
* ぐ段 → いで：泳ぐ→泳いで
* す段 → して：話す→して
* る段（上一段）→ て形／た形：食べる→食べて、見る→見て
* る段（下一段／五段）→ って：作る→作って、帰る→帰って
* 拗音（や・ゆ・よ）：喧嘩する→喧嘩して
"""

# 上一段活用（い段）
ICHIDAN = set('い')

# 下一段活用（え段・お段）→ て形是「って」
GODAN_UE_O = set('えお')


def godan_te(stem: str) -> tuple[str, str]:
    """五段活用的詞幹 → (て形, た形)。"""
    if not stem:
        return stem, stem
    last = stem[-1]
    if last in 'う':
        return stem[:-1] + 'って', stem[:-1] + 'った'
    if last in 'ぬぶむ':
        return stem[:-1] + 'んで', stem[:-1] + 'んだ'
    if last == 'く':
        return stem[:-1] + 'いて', stem[:-1] + 'いた'
    if last == 'ぐ':
        return stem[:-1] + 'いで', stem[:-1] + 'いだ'
    if last == 'す':
        return stem[:-1] + 'して', stem[:-1] + 'した'
    # 其他（い段 → て形；下一段 → って）
    if last in ICHIDAN:
        return stem + 'て', stem + 'た'
    if last in GODAN_UE_O:
        return stem[:-1] + 'って', stem[:-1] + 'った'
    return stem + 'て', stem + 'た'


def ichidan_te(stem: str) -> tuple[str, str]:
    """上一段活用 → (て形, た形)。"""
    if not stem:
        return stem, stem
    return stem[:-1] + 'て', stem[:-1] + 'た'


def te_form(stem: str, ichidan: bool) -> tuple[str, str]:
    return ichidan_te(stem) if ichidan else godan_te(stem)


def plain_of(masu: str) -> str:
    """ます形 → 字典形（含音便：書きます→書く、話します→話す）。

    規則：ます形去掉「ます」，剩下的詞幹：
      * 詞幹最後是「い」→ 寫作「く」（書きます→書く）
      * 詞幹最後是「し」→ 寫作「す」（話します→話す）
      * 其他 → 加「る」（食べます→食べる）
    不規則動詞（買います→買う）在 IRREGULAR_PLAIN 另外列。
    """
    if masu in IRREGULAR_PLAIN:
        return IRREGULAR_PLAIN[masu]
    if not masu.endswith('ます'):
        return masu
    stem = masu[:-2]
    if stem.endswith('い'):
        return stem[:-1] + 'く'
    if stem.endswith('し'):
        return stem[:-1] + 'す'
    return stem + 'る'


